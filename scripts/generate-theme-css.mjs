// Generate scoped color-only overrides from the existing stylesheet. The original
// dark-green stylesheet is left untouched; artwork and source brand badges are
// deliberately excluded. Run whenever the base color declarations change.
import fs from 'node:fs';
import postcss from 'postcss';
import {ACCENTS} from '../src/appearance.js';

const base=fs.readFileSync(new URL('../src/style.css',import.meta.url),'utf8');
const tree=postcss.parse(base);
const tokens=new Map();
const special=/\.hero(?:\b|-)|\.banner-text\b|\.detail-banner\b|\.trending-(?:number|image)\b|\.source-symbol\b|\.source-pill\b|\.tab-dot\b|\.cover-status\b|\.modal-backdrop\b|\.iframe-wrap\b/;
const reHex=/#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![0-9a-fA-F])/g;
function roleFor(prop) {
  if(prop==='color')return 'text';
  if(prop==='accent-color')return 'accent';
  if(prop==='scrollbar-color'||prop.startsWith('border'))return 'border';
  if(prop==='background'||prop==='background-color'||prop==='background-image')return 'bg';
  return '';
}
function expand(value) {
  let x=value.toLowerCase();
  if(x.length===3||x.length===4)x=[...x].map(n=>n+n).join('');
  return x;
}
function rgbToHsl(r,g,b) {
  r/=255;g/=255;b/=255;const mx=Math.max(r,g,b),mn=Math.min(r,g,b),d=mx-mn,l=(mx+mn)/2;
  if(!d)return [0,0,l];
  const s=d/(1-Math.abs(2*l-1));
  let h=mx===r?((g-b)/d)%6:mx===g?(b-r)/d+2:(r-g)/d+4;
  return [(h*60+360)%360,s,l];
}
function hslToHex(h,s,l,alpha='') {
  h=((h%360)+360)%360;s=Math.max(0,Math.min(1,s));l=Math.max(0,Math.min(1,l));
  const a=s*Math.min(l,1-l), f=n=>{const k=(n+h/30)%12;return l-a*Math.max(-1,Math.min(k-3,9-k,1));};
  return '#'+[f(0),f(8),f(4)].map(c=>Math.round(c*255).toString(16).padStart(2,'0')).join('')+alpha;
}
function transform(hex,role,mode,accent) {
  const full=expand(hex), rgb=full.slice(0,6), alpha=full.slice(6),
    [r,g,b]=[0,2,4].map(i=>parseInt(rgb.slice(i,i+2),16));
  let [h,s,l]=rgbToHsl(r,g,b);
  const green=h>=65&&h<=165&&s>=0.12;
  if(green)h+=accent.hue-95;
  if(mode==='dark')return hslToHex(h,s,l,alpha);
  if(role==='text') {
    if(l<.30){l=.97;s=.07;}
    else if(l>=.84){l=.15;s=Math.min(.34,s*.7);}
    else if(l>=.68){l=.22;s=Math.min(.42,s*.8);}
    else if(l>=.50){l=.30;s=Math.min(.40,s*.75);}
    else {l=.37;s=Math.min(.35,s*.7);}
  } else if(role==='bg') {
    if(l<.31){l=.985-l*.20;s=Math.min(.11,s*.45);}
    else if(l>=.55){l=.29;s=Math.max(.08,Math.min(.64,s*.9));}
    else {l=.88;s=Math.min(.18,s*.55);}
  } else if(role==='border') {
    if(l<.34){l=.84+(.34-l)*.08;s=Math.min(.12,s*.45);}
    else if(l>=.62){l=.36;s=Math.max(.10,Math.min(.55,s*.8));}
    else {l=.73;s=Math.min(.19,s*.55);}
  } else { // accent-color, e.g. native checkboxes
    return accent.light;
  }
  return hslToHex(h,s,l,alpha);
}

tree.walkComments(node=>node.remove());
tree.walkAtRules(node=>{if(node.name!=='media')node.remove();});
tree.walkRules(rule=>{
  // Brand/source badges and text placed directly on image gradients retain their
  // original contrasting colors. They must not be recolored as ordinary surfaces.
  if(!rule.selector||special.test(rule.selector)){rule.remove();return;}
  rule.walkDecls(decl=>{
    const role=roleFor(decl.prop);
    if(!role||!reHex.test(decl.value)){reHex.lastIndex=0;decl.remove();return;}
    reHex.lastIndex=0;
    let changed=false;
    const value=decl.value.replace(reHex,(all,hex)=>{
      const full=expand(hex);
      // Pure black and translucent black are deliberate cinema/image shadows.
      if(full.slice(0,6)==='000000')return all;
      const key=`${role}-${full}`;tokens.set(key,{hex:full,role});changed=true;
      return `var(--moku-${key},${all})`;
    });
    if(changed)decl.value=value;else decl.remove();
  });
  if(!rule.nodes?.length){rule.remove();return;}
  rule.selectors=rule.selectors.map(selector=>{
    const s=selector.trim();
    if(s===':root'||s==='html')return 'html[data-themed]';
    return 'html[data-themed] '+s;
  });
});
tree.walkAtRules(node=>{if(!node.nodes?.length)node.remove();});
const header='/* GENERATED by scripts/generate-theme-css.mjs — do not edit directly. */\n';
let palettes='';
for(const accent of ACCENTS)for(const mode of ['dark','light']) {
  if(mode==='dark'&&accent.id==='green')continue;
  let vars=[`--accent:${mode==='dark'?accent.dark:accent.light}`,`--bg:${mode==='dark'?accent.bgDark:accent.bgLight}`,
    `--hero-accent:${accent.dark}`,`--theme-ink:${mode==='dark'?'#1d2c1c':'#ffffff'}`];
  for(const [key,{hex,role}] of tokens)vars.push(`--moku-${key}:${transform(hex,role,mode,accent)}`);
  palettes+=`html[data-themed][data-mode="${mode}"][data-accent="${accent.id}"]{${vars.join(';')}}\n`;
}
const protect=`
html[data-themed]{background:var(--bg)}
/* Hero and detail art stay dark, with independently readable text and controls. */
html[data-mode="light"] .hero,html[data-mode="light"] .detail-banner{--accent:var(--hero-accent,#c8ee99)}
html[data-mode="light"] .hero .btn.primary{color:#1d2c1c}
html[data-mode="light"] .hero .btn.primary:hover{background:var(--hero-accent,#c8ee99);filter:brightness(1.08)}
/* The selected accent is the important signal, not a color from the old theme. */
html[data-themed] .nav-item.active,html[data-themed] .bottom-nav button.active{color:var(--accent)}
html[data-themed] .btn.primary,html[data-themed] .cover-badge,html[data-themed] .card-play,html[data-themed] .mark{color:var(--theme-ink)}
html[data-mode="light"]{color-scheme:light}
html[data-mode="dark"]{color-scheme:dark}
`;
fs.writeFileSync(new URL('../src/theme-generated.css',import.meta.url),header+palettes+tree.toString()+protect);
console.log(`Generated ${tokens.size} theme color tokens for 9 alternate mode/accent combinations.`);
